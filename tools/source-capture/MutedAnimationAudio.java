/** Graphics-only host: native animation steps run, but their audio events are deliberately not played. */
public final class MutedAnimationAudio extends aax
{
    public MutedAnimationAudio() { super(null); }
    @Override public void ab(ou sequence, int frame) { }
    @Override public void af(ou sequence, int frame) { }
    @Override public void is(ou sequence, int frame) { }
    @Override public void az(ou sequence, int frame, int guard) { }
    @Override public void ae(ou sequence, int frame) { }
    @Override public void ag(ou sequence, int frame) { }
}
